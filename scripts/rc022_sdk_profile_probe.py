import subprocess
import sys
from types import SimpleNamespace

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from scripts.oracles import sdk_profile_driver as driver

TARGET = '38a6a5c965aa99ab525161efb7cc5cf1fe62fced'
SOURCE_PATCH = '''- id: tool-fs
  disabled: true
- id: tool-working-directory
  disabled: true
- insert:
    - id: str-replace-editor
      name: '@deepseek-ai/dsh-tool-str-replace-editor'
      config:
        maxOutputChars: 16000
'''
UUID = re.compile(r'\b[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\b', re.I)


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def input_identity(source, node):
    def tracked(root, paths=()):
        raw = subprocess.check_output(['git', '-C', str(root), 'ls-files', '-z', '--cached',
                                       '--others', '--exclude-standard', '--', *paths])
        return {name: digest(root / name) for name in sorted(set(raw.decode('utf-8').split('\0')))
                if name and (root / name).is_file()}
    source_inputs = tracked(source)
    # Resolution can enter prepared Host libraries via package exports. Include
    # those generated bytes as well as the tracked Source tree and lockfile.
    for pattern in ['packages/*/*/lib/**/*', 'vendor/*/lib/**/*']:
        for path in source.glob(pattern):
            if path.is_file(): source_inputs[path.relative_to(source).as_posix()] = digest(path)
    return dict(source=source_inputs,
                native=tracked(ROOT, ['dsh', 'apps', 'packages', 'scripts', 'pyproject.toml', 'VERSION']),
                runtimes={str(path): digest(path) for path in
                    {node, Path(sys.executable).resolve(), Path(sys._base_executable).resolve()}})


def validate_runtime(capture, inputs):
    runtime = capture.get('runtime', {})
    if runtime.get('root') != str(ROOT) or not runtime.get('python', '').startswith('3.8.10 '):
        raise ValueError('Actual SDK did not import the selected Python 3.8.10 checkout')
    modules = runtime.get('modules', {})
    if not {'apps/cli/main.py', 'dsh/session/session_log_deepseek_current.py',
            'dsh/llm/deepseek_messages_adapter.py'} <= modules.keys():
        raise ValueError('Actual SDK import closure is incomplete')
    if any(inputs['native'].get(name) != value for name, value in modules.items()):
        raise ValueError('Actual SDK imported bytes outside the frozen input identity')


def facts(capture, destination):
    if capture.get('failure') or capture.get('exitCode') != 0 or capture.get('stderr') or capture.get('fixtureErrors'):
        raise ValueError('Actual process failed: ' + str(capture.get('failure', capture.get('stderr'))))
    ids = {}
    def normalize(value, key=None):
        if isinstance(value, dict):
            return {name: normalize(item, name) for name, item in value.items()}
        if isinstance(value, list):
            return [normalize(item, key) for item in value]
        if key in ('time', 'time0', 'createdAt'):
            if type(value) not in (int, float) or not capture['startedAt'] <= value <= capture['endedAt']:
                raise ValueError('Observed clock outside actual process interval')
            return '$CLOCK'
        if isinstance(value, str):
            for spelling in [str(destination).replace('\\', '\\\\'), str(destination),
                             str(destination).replace('\\', '/')]:
                value = value.replace(spelling, '$WORKSPACE')
            def identity(match):
                return ids.setdefault(match.group(0), '$UUID' + str(len(ids) + 1))
            return UUID.sub(identity, value)
        return value
    # Parse actual durable bytes, preserving every event and field. The
    # filename's escaped cwd is redundant with the retained exact header.
    if len(capture['logs']) != 1:
        raise ValueError('Expected one actual SDK-owned durable Session')
    log = [json.loads(line) for line in next(iter(capture['logs'].values())).splitlines()]
    return normalize(dict(requests=capture['requests'], frames=capture['frames'], log=log,
                          liveBarrier=capture.get('liveBarrier')))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ('source', 'node', 'output'):
        parser.add_argument('--' + name, type=Path, required=True)
    parser.add_argument('--scenario', choices=['normal', 'error', 'cancel'])
    args = parser.parse_args()
    source, node, output = args.source.resolve(), args.node.resolve(), args.output.absolute()
    output.relative_to(ROOT / '.goose/out'); output.mkdir(parents=True, exist_ok=False)
    if subprocess.check_output(['git', '-C', str(source), 'rev-parse', 'HEAD'], encoding='utf-8').strip() != TARGET:
        raise ValueError('Current Source pin differs')
    if subprocess.check_output(['git', '-C', str(source), 'status', '--porcelain'], encoding='utf-8').strip():
        raise ValueError('Current Source is dirty')
    if subprocess.check_output([str(node), '--version'], encoding='utf-8').strip() != 'v24.9.0':
        raise ValueError('Current Source Node version differs')
    old_path = os.environ['PATH']; os.environ['PATH'] = str(node.parent) + os.pathsep + old_path
    options = SimpleNamespace(source_root=source, native_root=ROOT, native_python=Path(sys.executable),
                              native_label='native', source_patch=SOURCE_PATCH, protocol='messages', tsconfig='tsconfig.base.json')
    report = dict(target_upstream=TARGET, node='v24.9.0', status='failed', scenarios=[])
    inputs = input_identity(source, node)
    (output / 'inputs.json').write_text(json.dumps(inputs, indent=2), encoding='utf-8')
    report['inputs_sha256'] = digest(output / 'inputs.json')
    try:
        for scenario in [args.scenario] if args.scenario else ['normal', 'error', 'cancel']:
            destination = output / scenario; destination.mkdir()
            captures = {side: driver.run(side, scenario, options, destination) for side in ('source', 'native')}
            validate_runtime(captures['native'], inputs)
            normalized = {side: facts(value, destination) for side, value in captures.items()}
            for side, value in normalized.items():
                (destination / (side + '.facts.json')).write_text(json.dumps(value, ensure_ascii=True, indent=2), encoding='utf-8')
            from scripts.session_format_oracle import json_equal
            equal = json_equal(normalized['source'], normalized['native'])
            report['scenarios'].append(dict(name=scenario, equal=equal))
            if not equal:
                raise ValueError('Current SDK complete process facts differ: ' + scenario)
        report['status'] = 'passed'
    except Exception as error:
        report['error'] = str(error)
        raise
    finally:
        os.environ['PATH'] = old_path
        report['observer_inputs'] = {name: hashlib.sha256((ROOT / name).read_bytes()).hexdigest() for name in
            ['scripts/rc022_sdk_profile_probe.py', 'scripts/model_http_fixture.py', 'scripts/oracles/sdk_profile_driver.py',
             'scripts/oracles/sdk_profile_source.mts', 'scripts/oracles/sdk_profile_python.py']}
        report['inputs_unchanged'] = inputs == input_identity(source, node)
        if not report['inputs_unchanged']: report.update(status='failed', error='Frozen process inputs changed')
        (output / 'report.json').write_text(json.dumps(report, ensure_ascii=True, indent=2), encoding='utf-8')
        if not report['inputs_unchanged']: raise ValueError('Frozen process inputs changed')
    print(report['status'])


if __name__ == '__main__':
    main()

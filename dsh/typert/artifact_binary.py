def remove_program(source):
    source = source.replace('\r\n', '\n')
    if 'const $resultSnapshot' not in source:return source, False
    if source.count(PROGRAM) != 1:
        raise ValueError('typert: unsupported generated byte-field program')
    return source.replace(PROGRAM, '', 1), True


def is_bytes(value):return isinstance(value, (bytes, bytearray, memoryview))


def encode_selected_data(value, write_bytes):
    """Snapshot once and extract only the declared data field, without parsing."""
    from dsh.typert.rpc_result import absent
    if absent(value):return value
    if value is None or isinstance(value, (str, bool, int, float)) or is_bytes(value) or callable(value):return value
    to_json = value.get('toJSON') if isinstance(value, dict) else getattr(value, 'toJSON', None)
    if isinstance(value, datetime.datetime) and not callable(to_json):
        instant=value if value.tzinfo is not None else value.replace(tzinfo=datetime.timezone.utc)
        return instant.astimezone(datetime.timezone.utc).isoformat(timespec='milliseconds').replace('+00:00', 'Z')
    projected = to_json('value') if callable(to_json) else value
    if absent(projected):return projected
    if projected is None or isinstance(projected, (str, bool, int, float)) or is_bytes(projected) or callable(projected):return projected
    if isinstance(projected, (list, tuple)):return list(projected)
    fields = projected if isinstance(projected, dict) else vars(projected) if hasattr(projected, '__dict__') else {}
    result = {}
    for key in _js_own_enumerable_keys(fields):
        item = to_json if key == 'toJSON' and projected is value else fields[key]
        if key == 'toJSON' and callable(item):continue
        result[key] = item
    if 'data' in result and is_bytes(result['data']):result['data'] = write_bytes(result['data'], ['data'])
    return result
